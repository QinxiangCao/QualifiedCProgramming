"""Structural checks for the generation groups (no proof search)."""
import collections
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = json.loads((ROOT / 'scripts/split-generation-manifest.json').read_text())


def baseline(path):
    return subprocess.check_output(
        ['git', 'show', f"{MANIFEST['base_commit']}:{path}"], cwd=ROOT
    ).decode('utf-8')


def read(path):
    return (ROOT / path).read_text(encoding='utf-8')


def definitions(text):
    text = text.split('Module Type VC_Correct.')[0]
    text = re.sub(r'\(\*----- Function \w+ -----\*\)', '', text)
    starts = list(re.finditer(r'^Definition (\w+)\b', text, re.M))
    return {m[1]: text[m.start():starts[i+1].start() if i+1 < len(starts) else len(text)].strip()
            for i, m in enumerate(starts)}


def lemmas(text):
    return dict(re.findall(
        r'(?m)^Lemma (\w+)\b([\s\S]*?)(?:^Qed\.|^Defined\.|^Admitted\.|^Proof\. Admitted\.)',
        text))


def test_manual_proof_partition_is_preserved():
    # Goals and auto proofs are regenerated by the current frontend and may
    # rename/split witnesses. Keep the original handwritten proof bodies intact;
    # their compatibility with the refreshed goals is checked by Rocq separately.
    for case in MANIFEST['cases']:
        base = f"Rocq/examples/Applications_human/{case['folder']}/{case['stem']}"
        old_manual, new_manual = {}, {}
        for p in (ROOT / base).parent.glob(case['stem'] + '_proof_manual_part*.v'):
            old_manual.update(lemmas(baseline(p.relative_to(ROOT).as_posix())))
        for unit in case['units']:
            block = lemmas(read(unit['rocq_stem'] + '_proof_manual.v'))
            assert not new_manual.keys() & block.keys()
            new_manual.update(block)
        assert new_manual == old_manual


def native_text(text):
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)
    return re.sub(r'\s+', '', text)


def native_function(text, name):
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)
    match = re.search(r'(?m)^[\w \t*]+\b' + re.escape(name) +
                      r'\s*\([^;{}]*\)\s*\{', text)
    assert match, f'missing definition: {name}'
    depth = 1
    end = match.end()
    while depth:
        depth += (text[end] == '{') - (text[end] == '}')
        end += 1
    # Cross-file helpers now have external linkage; their native bodies and
    # parameter types must still match the historical implementation.
    return native_text(re.sub(r'\b(?:static|inline)\s+', '', text[match.start():end]))


def test_native_implementation_and_function_partition_are_preserved():
    for case in MANIFEST['cases']:
        all_functions = []
        independent = case.get('layout') == 'translation_units'
        if independent:
            assert not (ROOT / case['baseline_source']).exists()
            for path in (ROOT / case['case']).glob('*.[ch]'):
                assert 'QCP_SPLIT_' not in path.read_text()
                assert not re.search(r'#include\s+"[^"]+\.c"', path.read_text())
        for unit in case['units']:
            wrapper = read(unit['source'])
            if not independent:
                assert '#define QCP_SPLIT_UNIT 1' in wrapper
                assert f'#include "{case["stem"]}.c"' in wrapper
                assert set(re.findall(r'^#define QCP_SPLIT_(\w+) 1$', wrapper, re.M)) == set(unit['functions']) | {'UNIT'}
            all_functions.extend(unit['functions'])
            for function in unit['functions']:
                origin = unit['origins'][function]
                old = baseline(origin)
                if independent:
                    assert native_function(wrapper, function) == native_function(old, function), function
                    continue
                # Annotation syntax is migrated, while native definitions stay unchanged.
                current = read(origin)
                selected = current.split(f'#if !defined(QCP_SPLIT_UNIT) || defined(QCP_SPLIT_{function})\n', 1)[1]
                selected = selected.split('\n#else\n', 1)[0]
                assert native_text(selected) in native_text(old)
        assert len(all_functions) == len(set(all_functions))
        base = f"Rocq/examples/Applications_human/{case['folder']}/{case['stem']}_goal.v"
        assert set(all_functions) == set(re.findall(r'\(\*----- Function (\w+) -----\*\)', baseline(base)))


def test_each_unit_is_discovered_by_shared_generation_entry():
    import sys
    sys.path.insert(0, str(ROOT / "scripts"))
    from generation_tasks import ProgramVC, discover_programs, outputs
    tasks = set(discover_programs())
    for case in MANIFEST["cases"]:
        assert ProgramVC(Path(case["case"])) not in tasks
        for unit in case["units"]:
            task = ProgramVC(Path(unit["source"]))
            assert task in tasks
            destinations = {str(file.source) for file in outputs(task)}
            for suffix in ("goal", "proof_auto", "proof_manual"):
                assert unit["rocq_stem"] + "_" + suffix + ".v" in destinations


def test_aggregate_goal_preserves_strategy_import_visibility():
    # Re-exporting a group's goal does not re-export its Require Import context.
    # The aggregate VC_Correct also includes strategy module types, so it needs
    # the original imports in its own compilation unit.
    for case in MANIFEST['cases']:
        path = f"Rocq/examples/Applications_human/{case['folder']}/{case['stem']}_goal.v"
        old_header = baseline(path).split('(*----- Function', 1)[0]
        required = set(re.findall(r'^(?:From .+ )?Require Import .+\.$', old_header, re.M))
        current = set(read(path).splitlines())
        assert required <= current


def test_split_proof_imports_have_no_cycles_or_missing_units():
    graph = collections.defaultdict(set)
    for case in MANIFEST['cases']:
        prefix = f"SimpleC.EE.Applications_human.{case['folder']}."
        paths = list((ROOT / 'Rocq/examples/Applications_human' / case['folder']).glob('*.v'))
        modules = {p.stem for p in paths}
        for path in paths:
            text = path.read_text(encoding='utf-8')
            imports = re.findall(r'^Require (?:Import|Export) ' + re.escape(prefix) + r'(\w+)\.', text, re.M)
            for group in re.findall(r'^From ' + re.escape(prefix[:-1]) + r' Require (?:Import|Export) ([^.]+)\.', text, re.M):
                imports.extend(group.split())
            assert set(imports) <= modules
            graph[prefix + path.stem].update(prefix + name for name in imports)
    done, active = set(), set()

    def visit(node):
        assert node not in active, f'import cycle at {node}'
        if node in done:
            return
        active.add(node)
        for dependency in graph[node]:
            visit(dependency)
        active.remove(node)
        done.add(node)

    for node in list(graph):
        visit(node)
