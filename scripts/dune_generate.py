#!/usr/bin/env python3
"""Generate Dune rules and candidate artifacts; Dune owns scheduling and promotion."""

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import generation_tasks as tasks


def quote(path: Path | str) -> str:
    return json.dumps(path.as_posix() if isinstance(path, Path) else path)


def rule_names(directories: list[Path]) -> dict[Path, str]:
    hashes = {directory: hashlib.sha256(directory.as_posix().encode()).hexdigest()
              for directory in sorted(set(directories))}
    if len(set(hashes.values())) != len(hashes):
        raise ValueError('Directory hash collision')
    return {directory: next(digest[:length] + '.inc' for length in range(1, 65)
                            if sum(other.startswith(digest[:length])
                                   for other in hashes.values()) == 1)
            for directory, digest in hashes.items()}


def directory_closure(directories: list[Path]) -> list[Path]:
    """Return every directory and ancestor, including the virtual root."""
    closure = {Path('.')}
    for directory in directories:
        while directory != Path('.'):
            closure.add(directory)
            directory = directory.parent
    return sorted(closure)


def configure(root: Path) -> str:
    names = rule_names([task.source.relative_to(tasks.SOURCES).parent
                        for task in tasks.discover_vcs(root)])
    parts = ['''; Generated by scripts/dune_generate.py. Refresh with:
; dune build @gen-dune-config --auto-promote
; @gen-vcs includes C programs and non-builtin strategies.

(alias (name generate) (deps (alias gen-builtin) (alias_rec gen-vcs)))
(alias (name gen-vcs) (deps (alias gen-dune-config) (alias gen-builtin)))
(alias (name gen-builtin) (deps (alias gen-builtin/export)))

(rule
 (alias gen-dune-config)
 (deps (glob_files_rec QCP_examples/*.c)
       (glob_files_rec QCP_examples/*.strategies)
       scripts/generation_tasks.py scripts/binaries.py)
 (action
  (progn
   (with-stdout-to dune.gen
    (run python3 %{dep:scripts/dune_generate.py} configure %{workspace_root}))
   (diff dune dune.gen))))

(subdir gen-rules/builtin
 (rule
  (deps ../../scripts/generation_tasks.py ../../scripts/binaries.py
        (glob_files_rec ../../bin/*))
  (action
   (with-stdout-to rules.inc
    (run python3 %{dep:../../scripts/dune_generate.py} builtin-rules %{workspace_root})))))
(subdir gen-builtin (dynamic_include ../gen-rules/builtin/rules.inc))
''']
    if names:
        parts.append(f'''(subdir gen-rules
 (rule
  (targets {' '.join(names.values())})
  (deps (glob_files_rec ../QCP_examples/*.{{c,strategies}})
        ../scripts/generation_tasks.py ../scripts/binaries.py)
  (action
   (run python3 %{{dep:../scripts/dune_generate.py}} rules %{{workspace_root}} %{{targets}}))))''')
    for directory in directory_closure(list(names)):
        stanzas = ['(alias (name default) (deps (alias_rec gen-vcs)))']
        if directory in names:
            prefix = '/'.join(['..'] * (len(directory.parts) + 1))
            stanzas.append(
                f'(dynamic_include {quote(Path(prefix) / "gen-rules" / names[directory])})')
        body = '\n '.join(stanzas)
        parts.append(f'''(subdir {quote(Path('gen-vcs') / directory)}
 {body})''')
    return "\n".join(parts) + "\n"


def task_rule(task: tasks.GenerationTask, files: list[tasks.GeneratedFile]) -> str:
    builtin = isinstance(task, tasks.BuiltinExport)
    source = None if builtin else task.source
    prefix = '..' if builtin else '/'.join(['..'] * len(source.relative_to(tasks.SOURCES).parts))
    candidate = Path('candidates') if builtin else Path(source.name)
    name = 'export' if builtin else source.name
    kind = next(key for key, cls in tasks.TASK_TYPES.items() if isinstance(task, cls))
    deps = [f'(alias {prefix}/gen-dune-config)',
            f'{prefix}/scripts/generation_tasks.py', f'{prefix}/scripts/binaries.py',
            f'(glob_files_rec {prefix}/bin/*)']
    if not builtin:
        deps += [f'(alias {prefix}/gen-builtin)', quote(Path(prefix) / source),
                 f'(glob_files_rec {prefix}/QCP_examples/*.h)',
                 f'(glob_files_rec {prefix}/QCP_examples/*.strategies)']
    diffs = [f'(diff? {quote(Path(prefix) / file.source)} {quote(candidate / file.candidate)})'
             for file in files]
    aggregate = '' if builtin else f'(alias (name gen-vcs) (deps (alias {quote(name)})))\n'
    source_arg = '' if builtin else ' ' + quote(source)
    return aggregate + f'''(rule
 (alias {quote(name)})
 (deps {' '.join(deps)})
 (action
  (progn
   (run python3 %{{dep:{prefix}/scripts/dune_generate.py}} generate %{{workspace_root}}
        {kind} {quote(candidate)}{source_arg})
   (concurrent {' '.join(diffs)}))))
'''


def rules(root: Path, targets: list[Path]) -> None:
    grouped = {}
    for task in tasks.discover_vcs(root):
        directory = task.source.relative_to(tasks.SOURCES).parent
        grouped.setdefault(directory, []).append(task)
    names = rule_names(list(grouped))
    if set(names.values()) != {target.name for target in targets}:
        raise SystemExit('Dune configuration is outdated; run '
                         'dune build @gen-dune-config --auto-promote')
    for directory, name in names.items():
        entries = (task_rule(task, tasks.outputs(task)) for task in grouped[directory])
        content = f'; QCP_examples/{directory.as_posix()}\n' + '\n'.join(entries)
        Path(name).write_text(content)


def generate(root: Path, task: tasks.GenerationTask, destination: Path,
             *, preserve_manual: bool = True) -> list[tasks.GeneratedFile]:
    root = root.resolve()
    destination = destination.resolve()
    # These are private task candidates, never source-tree artifacts. Fresh output
    # avoids stale optional files and the tool's existing-definition suppression.
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    builtin = isinstance(task, tasks.BuiltinExport)
    proof_dir = destination / 'proofs' if builtin else destination
    proof_dir.mkdir(exist_ok=True)
    export_dir = destination / 'strategies' if builtin else None
    args, _ = tasks.command(task, output=proof_dir, builtin_export=export_dir,
                            manual_templates=True)
    result = subprocess.run(args, cwd=root, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, encoding='utf-8', errors='replace')
    if result.returncode:
        sys.stderr.write(result.stdout)
        raise SystemExit(result.returncode)
    names = sorted(path.stem for path in export_dir.glob('*.strategies')) if builtin else ()
    if builtin and not names:
        raise RuntimeError('Builtin export produced no strategy snapshots')
    files = tasks.outputs(task, names)
    for file in files:
        path = destination / file.candidate
        if not file.optional and not path.is_file():
            raise RuntimeError(f'Missing generated output: {path}; use tools supporting '
                               '--proof-manual-as-template for strategy proofs')
        if file.manual and preserve_manual and (root / file.source).exists():
            path.unlink()
    return files


def builtin_rules(root: Path) -> None:
    # Inventory comes from the tool, not old snapshots: newly added builtin
    # libraries must also get diff/promote rules. This probe is cached by Dune.
    with tempfile.TemporaryDirectory(prefix='qcp-builtin-inventory-') as tmp:
        files = generate(root, tasks.BuiltinExport(), Path(tmp) / 'export',
                         preserve_manual=False)
    print(task_rule(tasks.BuiltinExport(), files))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    for name in ('configure', 'rules', 'builtin-rules', 'generate'):
        sub = commands.add_parser(name)
        sub.add_argument('root', type=Path)
        if name == 'rules':
            sub.add_argument('targets', type=Path, nargs='+')
        elif name == 'generate':
            sub.add_argument('kind', choices=tasks.TASK_TYPES)
            sub.add_argument('destination', type=Path)
            sub.add_argument('source', type=Path, nargs='?')
    args = parser.parse_args()
    if args.command == 'configure':
        content = configure(args.root)
        current = args.root / 'dune'
        if current.exists() and current.read_text() != content:
            print('Dune configuration is outdated.\n'
                  'Run "dune promote dune" to update it.', file=sys.stderr)
        sys.stdout.write(content)
    elif args.command == 'rules':
        rules(args.root, args.targets)
    elif args.command == 'builtin-rules':
        builtin_rules(args.root)
    else:
        if (args.kind == 'builtin') != (args.source is None):
            parser.error('program/strategy require a source; builtin does not accept one')
        task = tasks.BuiltinExport() if args.kind == 'builtin' else tasks.TASK_TYPES[args.kind](args.source)
        generate(args.root, task, args.destination)


if __name__ == '__main__':
    main()
